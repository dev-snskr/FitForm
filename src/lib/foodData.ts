// Helper to filter allowed foods by user diet type and exclusions
export function getAvailableFoods(
  dietType: DietType,
  excludedFoodIds: string[] = []
): FoodItem[] {
  return FOOD_DATABASE.filter((food) => {
    // Check exclusions
    if (excludedFoodIds.includes(food.id)) return false;

    // Filter by dietType compatibility
    if (dietType === 'vegetarian') {
      return food.dietType === 'vegetarian';
    }
    if (dietType === 'eggetarian') {
      return food.dietType === 'vegetarian' || food.dietType === 'eggetarian';
    }
    // non-vegetarian eats everything
    return true;
  });
}

// Helper to get top cheapest protein foods
export function getTopCheapestProteins(dietType: DietType, count: number = 5): FoodItem[] {
  const allowed = getAvailableFoods(dietType);
  return allowed
    .filter((f) => f.protein >= 5) // meaningful protein content
    .sort((a, b) => b.proteinPerRupee - a.proteinPerRupee)
    .slice(0, count);
}
